import { extractInvoice } from "@ledgerpilot/agent";
import { buildDegradedCases, buildSupportedCases } from "./dataset";
import { FIELDS, scoreExtraction, type ExtractionReport, type FieldScore } from "./extraction";
import { runSecurityCases, type SecurityResult } from "./security";

/**
 * The evaluation runner, as a pure function of the code under test.
 *
 * `pnpm eval` renders the report; the test suite asserts the same thresholds, so
 * a regression fails CI before anyone reads a document.
 */

export interface Thresholds {
  readonly fieldF1: number;
  readonly lineF1: number;
  readonly degradedPassRate: number;
  readonly securityPassRate: number;
}

export const THRESHOLDS: Thresholds = {
  fieldF1: 0.9,
  lineF1: 0.9,
  degradedPassRate: 1,
  securityPassRate: 1,
};

export interface DegradedResult {
  readonly id: string;
  readonly locale: string;
  readonly reason: string;
  readonly expectation: string;
  readonly passed: boolean;
  readonly detail: string | null;
}

export interface EvalRun {
  readonly extraction: ExtractionReport;
  readonly degraded: readonly DegradedResult[];
  readonly security: readonly SecurityResult[];
  readonly rates: {
    readonly fieldF1: number;
    readonly lineF1: number;
    readonly degradedPassRate: number;
    readonly securityPassRate: number;
  };
  readonly passed: {
    readonly fieldF1: boolean;
    readonly lineF1: boolean;
    readonly degraded: boolean;
    readonly security: boolean;
  };
  readonly overall: boolean;
}

export function runEvals(): EvalRun {
  const supported = buildSupportedCases();
  const extraction = scoreExtraction(supported, extractInvoice);

  const degraded: DegradedResult[] = buildDegradedCases().map((testCase) => {
    const detail = testCase.check(extractInvoice(testCase.text));
    return {
      id: testCase.id,
      locale: testCase.locale,
      reason: testCase.reason,
      expectation: testCase.expectation,
      passed: detail === null,
      detail,
    };
  });

  const security = runSecurityCases();

  const rates = {
    fieldF1: extraction.micro.f1,
    lineF1: extraction.lines.f1,
    degradedPassRate: degraded.filter((result) => result.passed).length / degraded.length,
    securityPassRate: security.filter((result) => result.passed).length / security.length,
  };

  const passed = {
    fieldF1: rates.fieldF1 >= THRESHOLDS.fieldF1,
    lineF1: rates.lineF1 >= THRESHOLDS.lineF1,
    degraded: rates.degradedPassRate >= THRESHOLDS.degradedPassRate,
    security: rates.securityPassRate >= THRESHOLDS.securityPassRate,
  };

  return {
    extraction,
    degraded,
    security,
    rates,
    passed,
    overall: Object.values(passed).every(Boolean),
  };
}

function percent(value: number): string {
  return `${(value * 100).toFixed(1)}%`;
}

function mark(pass: boolean): string {
  return pass ? "pass" : "FAIL";
}

function fieldRow(score: FieldScore): string {
  return `| \`${score.field}\` | ${score.tp} | ${score.fp} | ${score.fn} | ${percent(score.precision)} | ${percent(score.recall)} | **${percent(score.f1)}** |`;
}

export function renderReport(run: EvalRun, generatedAt: string): string {
  const { extraction } = run;
  const failures = extraction.failures;

  const lines: string[] = [
    "# Evaluation report",
    "",
    `Generated by \`pnpm eval\` on ${generatedAt}. Deterministic, offline, no API key.`,
    "",
    "The same checks run in `packages/evals/src/evals.test.ts`, so this report cannot",
    "drift from the test suite without failing it.",
    "",
    "## Summary",
    "",
    "| Metric | Result | Threshold | Status |",
    "| --- | --- | --- | --- |",
    `| Field F1 (micro, ${FIELDS.length} fields × ${extraction.cases} invoices) | ${percent(run.rates.fieldF1)} | ≥ ${percent(THRESHOLDS.fieldF1)} | ${mark(run.passed.fieldF1)} |`,
    `| Line-item F1 | ${percent(run.rates.lineF1)} | ≥ ${percent(THRESHOLDS.lineF1)} | ${mark(run.passed.lineF1)} |`,
    `| Degraded-document behaviour | ${percent(run.rates.degradedPassRate)} | ${percent(THRESHOLDS.degradedPassRate)} | ${mark(run.passed.degraded)} |`,
    `| Security cases | ${percent(run.rates.securityPassRate)} | ${percent(THRESHOLDS.securityPassRate)} | ${mark(run.passed.security)} |`,
    "",
    `**Overall: ${run.overall ? "pass" : "FAIL"}.** ${extraction.perfectCases}/${extraction.cases} invoices were extracted with every field correct.`,
    "",
    "## Extraction, per field",
    "",
    "| Field | TP | FP | FN | Precision | Recall | F1 |",
    "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ...extraction.fields.map(fieldRow),
    `| **All fields** | **${extraction.micro.tp}** | **${extraction.micro.fp}** | **${extraction.micro.fn}** | **${percent(extraction.micro.precision)}** | **${percent(extraction.micro.recall)}** | **${percent(extraction.micro.f1)}** |`,
    "",
    "A field is a true positive only when it is exactly right. An invented value is",
    "counted as both a false positive and a false negative: attaching an invoice to the",
    "wrong record is worse than leaving it for a human.",
    "",
  ];

  if (failures.length > 0) {
    lines.push("### Field failures", "", "| Case | Field | Expected | Extracted |", "| --- | --- | --- | --- |");
    for (const failure of failures) {
      lines.push(
        `| ${failure.caseId} | \`${failure.field}\` | ${failure.expected} | ${failure.actual} |`,
      );
    }
    lines.push("");
  }

  lines.push(
    "## Degraded documents",
    "",
    "These documents are intentionally incomplete or unreadable. The expectation is not",
    "perfect extraction; it is honest behaviour: null instead of invented, and a warning",
    "a human can act on.",
    "",
    "| Case | Language | Problem | Expectation | Status |",
    "| --- | --- | --- | --- | --- |",
  );
  for (const result of run.degraded) {
    lines.push(
      `| ${result.id} | ${result.locale} | ${result.reason} | ${result.expectation} | ${mark(result.passed)}${result.detail ? `: ${result.detail}` : ""} |`,
    );
  }

  lines.push(
    "",
    "## Security",
    "",
    "The boundary the product depends on: documents are data, proposals are not",
    "executions, and a human is always in the loop.",
    "",
    "| Case | Area | What must hold | Status |",
    "| --- | --- | --- | --- |",
  );
  for (const result of run.security) {
    lines.push(
      `| ${result.id} | ${result.area} | ${result.description} | ${mark(result.passed)}${result.detail ? `: ${result.detail}` : ""} |`,
    );
  }

  lines.push(
    "",
    "## What this measures, and what it does not",
    "",
    "- The supported corpus is synthetic and in-distribution: labelled text-layer",
    "  invoices in English and Spanish, two layouts, four currencies, both decimal",
    "  conventions. It is a regression harness, not a claim about arbitrary scans.",
    "- Scanned documents without a text layer are expected to fail extraction and be",
    "  routed to review. OCR is a separate capability; the eval asserts the fallback",
    "  behaviour, not OCR quality.",
    "- Ambiguous numeric dates (`03/04/2026`) are not scored for correctness. The",
    "  degraded set checks the honest alternative: keep the value, drop the confidence",
    "  below the review threshold and warn.",
    "- Security cases are deterministic unit-level checks of the policy engine, the",
    "  injection scanner and the execution gate. They complement, but do not replace,",
    "  an end-to-end test against the running server.",
    "",
  );

  return lines.join("\n");
}
